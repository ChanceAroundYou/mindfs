#!/usr/bin/env python3
"""从 internal/brand/brand.json 生成所有非 Go 的品牌落点。

Go 代码直接 import internal/brand；前端与原生/安装器没有跨语言 import，
所以由本脚本把同一个 JSON 写进生成文件与模板。改完 brand.json 后跑：

    make brand-sync

`--check` 只比对不写，供测试/门禁使用；不一致时列出哪些文件需要重新生成。

边界：只写**展示名**。注册表键、安装目录、配置目录、协议头、桥对象名等
安装/协议身份故意保持 "mindfs"/"MindFS" 不变（见 internal/brand/brand.go）。
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "internal/brand/brand.json"
MARKER = "Generated from internal/brand/brand.json by scripts/brand-sync.py"


def load_brand() -> dict[str, str]:
    try:
        data = json.loads(SOURCE.read_text(encoding="utf-8"))
    except FileNotFoundError:
        sys.exit(f"missing brand source: {SOURCE}")
    except json.JSONDecodeError as exc:
        sys.exit(f"invalid {SOURCE}: {exc}")
    for key in ("name", "tagline", "description"):
        value = data.get(key)
        if not isinstance(value, str) or not value.strip() or value != value.strip():
            sys.exit(f"brand.json: {key} must be a non-empty, trimmed string")
    return data


def brand_ts(brand: dict[str, str]) -> str:
    def lit(value: str) -> str:
        return json.dumps(value, ensure_ascii=False)

    return (
        f"// Code generated by scripts/brand-sync.py from internal/brand/brand.json; DO NOT EDIT.\n"
        f"export const BRAND = {{\n"
        f"  name: {lit(brand['name'])},\n"
        f"  tagline: {lit(brand['tagline'])},\n"
        f"  description: {lit(brand['description'])},\n"
        f"}} as const;\n"
        f"\n"
        f"export const APP_DOCUMENT_TITLE = BRAND.name;\n"
    )


def patch_manifest(path: Path, brand: dict[str, str]) -> str:
    data = json.loads(path.read_text(encoding="utf-8"))
    data["name"] = brand["name"]
    data["short_name"] = brand["name"]
    data["description"] = f"{brand['name']} {brand['description']}"
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def patch_capacitor(path: Path, brand: dict[str, str]) -> str:
    data = json.loads(path.read_text(encoding="utf-8"))
    data["appName"] = brand["name"]
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def patch_index_html(path: Path, brand: dict[str, str]) -> str:
    text = path.read_text(encoding="utf-8")
    return re.sub(r"<title>.*?</title>", f"<title>{brand['name']}</title>", text, count=1)


def patch_offline_html(path: Path, brand: dict[str, str]) -> str:
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"<title>.*? Offline</title>", f"<title>{brand['name']} Offline</title>", text, count=1)
    text = re.sub(r"<p>.*? 已安装为 PWA", f"<p>{brand['name']} 已安装为 PWA", text, count=1)
    return text


def patch_android_strings(path: Path, brand: dict[str, str]) -> str:
    text = path.read_text(encoding="utf-8")
    for key in ("app_name", "title_activity_main"):
        text = re.sub(
            rf'(<string name="{key}">).*?(</string>)',
            lambda m: m.group(1) + brand["name"] + m.group(2),
            text,
            count=1,
        )
    return text


def patch_ios_plist(path: Path, brand: dict[str, str]) -> str:
    text = path.read_text(encoding="utf-8")
    return re.sub(
        r"(<key>CFBundleDisplayName</key>\s*<string>).*?(</string>)",
        lambda m: m.group(1) + brand["name"] + m.group(2),
        text,
        count=1,
        flags=re.DOTALL,
    )


def patch_nsis(path: Path, brand: dict[str, str]) -> str:
    text = path.read_text(encoding="utf-8")
    return re.sub(
        r'(!ifndef APP_NAME\s*\n\s*!define APP_NAME ").*?("\s*\n!endif)',
        lambda m: m.group(1) + brand["name"] + m.group(2),
        text,
        count=1,
    )


def patch_ps1(path: Path, brand: dict[str, str]) -> str:
    text = path.read_text(encoding="utf-8")
    name = brand["name"]
    if not name.isascii():
        sys.exit(f"{path}: Windows PowerShell reads this file as ANSI; brand name must be ASCII")
    return re.sub(
        r'(\$BrandName = )(["\']).*?\2',
        lambda m: m.group(1) + m.group(2) + name + m.group(2),
        text,
        count=1,
    )


def targets(brand: dict[str, str]) -> dict[Path, str]:
    return {
        ROOT / "web/src/shared/brand.ts": brand_ts(brand),
        ROOT / "web/public/manifest.webmanifest": patch_manifest(
            ROOT / "web/public/manifest.webmanifest", brand
        ),
        ROOT / "web/public/manifest-light.webmanifest": patch_manifest(
            ROOT / "web/public/manifest-light.webmanifest", brand
        ),
        ROOT / "web/capacitor.config.json": patch_capacitor(ROOT / "web/capacitor.config.json", brand),
        ROOT / "web/index.html": patch_index_html(ROOT / "web/index.html", brand),
        ROOT / "web/public/offline.html": patch_offline_html(ROOT / "web/public/offline.html", brand),
        ROOT / "web/android/app/src/main/res/values/strings.xml": patch_android_strings(
            ROOT / "web/android/app/src/main/res/values/strings.xml", brand
        ),
        ROOT / "web/ios/App/App/Info.plist": patch_ios_plist(ROOT / "web/ios/App/App/Info.plist", brand),
        ROOT / "scripts/windows-installer/mindfs.nsi": patch_nsis(
            ROOT / "scripts/windows-installer/mindfs.nsi", brand
        ),
        ROOT / "scripts/install.ps1": patch_ps1(ROOT / "scripts/install.ps1", brand),
        ROOT / "scripts/windows-setup/setup.ps1": patch_ps1(ROOT / "scripts/windows-setup/setup.ps1", brand),
        ROOT / "scripts/pcwin/codex-switch.ps1": patch_ps1(ROOT / "scripts/pcwin/codex-switch.ps1", brand),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="只检查是否与 brand.json 同步")
    args = parser.parse_args()

    brand = load_brand()
    stale: list[Path] = []
    for path, expected in targets(brand).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != expected:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected, encoding="utf-8")

    if args.check:
        if stale:
            print("brand 产物与 internal/brand/brand.json 不一致：", file=sys.stderr)
            for path in stale:
                print(f"  - {path.relative_to(ROOT)}", file=sys.stderr)
            print("运行 `make brand-sync` 重新生成。", file=sys.stderr)
            return 1
        print("brand 产物已同步。")
        return 0

    for path in stale:
        print(f"updated {path.relative_to(ROOT)}")
    if not stale:
        print("brand 产物已是最新。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())